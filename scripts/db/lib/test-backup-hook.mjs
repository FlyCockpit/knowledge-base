/** Synthetic result producer for runner tests ONLY; never a recoverable KB bundle. */
import { writeFileSync } from "node:fs";
import path from "node:path";

export function writeTestBackupHook(dir, { logFile, failFile } = {}) {
  const script = path.join(dir, "fixture-backup.mjs");
  writeFileSync(
    script,
    `
import fs from "node:fs";
import path from "node:path";
import {createHash} from "node:crypto";
const env=process.env;
const logFile=${JSON.stringify(logFile ?? null)};
const failFile=${JSON.stringify(failFile ?? null)};
if(logFile) fs.appendFileSync(logFile,process.argv.slice(2).join(" ")+"\\n");
if(failFile && fs.existsSync(failFile)) process.exit(1);
const bundlePath=path.join(${JSON.stringify(dir)},"backup-"+env.KB_BACKUP_RUN_ID+".age");
const bytes="TEST FIXTURE ONLY - not an encrypted recovery bundle";
fs.writeFileSync(bundlePath,bytes);
const marker=JSON.stringify({version:1,size:Buffer.byteLength(bytes),sha256:createHash("sha256").update(bytes).digest("hex")});
fs.writeFileSync(bundlePath+".complete",marker);
const createdAt=new Date().toISOString();
fs.writeFileSync(env.BACKUP_RESULT_FILE,JSON.stringify({version:1,runId:env.KB_BACKUP_RUN_ID,label:process.argv[process.argv.indexOf("--label")+1],createdAt,utcDay:createdAt.slice(0,10),bundlePath,completion:{path:bundlePath+".complete",sha256:createHash("sha256").update(marker).digest("hex")},upload:{configured:false,outcome:"local-only"}}));
`,
  );
  const hook = path.join(dir, "fixture-backup.sh");
  // Temp paths are generated by our test harness, never caller shell text.
  writeFileSync(hook, `${JSON.stringify(process.execPath)} ${JSON.stringify(script)} "$@"\n`);
  return hook;
}
